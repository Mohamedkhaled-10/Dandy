function escapeAttr(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

export function isSupportedIcon(name: string): name is DandyIconName {
  return Object.prototype.hasOwnProperty.call(ICON_PATHS, name);
}

export function getIconInnerSvg(name: DandyIconName): string {
  return isSupportedIcon(name) ? ICON_PATHS[name] : ICON_PATHS['info'];
}

/**
 * Returns safe, uniform Lucide SVG markup for client-side JS templates.
 */
export function getIconSvg(
  name: DandyIconName,
  options: IconSvgOptions = {}
): string {
  const safeName: DandyIconName = isSupportedIcon(name) ? name : 'info';
  const size = Number.isFinite(options.size) && (options.size as number) > 0 ? Math.round(options.size as number) : 18;
  const strokeWidth = Number.isFinite(options.strokeWidth) && (options.strokeWidth as number) > 0
    ? Number(options.strokeWidth)
    : 1.75;
  const classAttr = options.className
    ? ` class="dandy-icon ${escapeAttr(options.className)}"`
    : ' class="dandy-icon"';
  const a11yAttr = options.ariaLabel
    ? ` role="img" aria-label="${escapeAttr(options.ariaLabel)}"`
    : ' aria-hidden="true"';

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round"${classAttr}${a11yAttr}>${ICON_PATHS[safeName]}</svg>`;
}

/**
 * Safely populates an existing SVG element or creates one via DOM without innerHTML injection from untrusted strings.
 */
export function createIconElement(
  doc: Document,
  name: DandyIconName,
  options: IconSvgOptions = {}
): SVGSVGElement {
  const SVG_NS = 'http://www.w3.org/2000/svg';
  const svg = doc.createElementNS(SVG_NS, 'svg');
  const size = Number.isFinite(options.size) && (options.size as number) > 0 ? Math.round(options.size as number) : 18;
  const strokeWidth = Number.isFinite(options.strokeWidth) && (options.strokeWidth as number) > 0
    ? Number(options.strokeWidth)
    : 1.75;

  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', String(strokeWidth));
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('class', options.className ? `dandy-icon ${options.className}` : 'dandy-icon');

  if (options.ariaLabel) {
    svg.setAttribute('role', 'img');
    svg.setAttribute('aria-label', options.ariaLabel);
  } else {
    svg.setAttribute('aria-hidden', 'true');
  }

  // Static registry SVG path fragments only (no user input)
  svg.innerHTML = getIconInnerSvg(name);
  return svg;
}
